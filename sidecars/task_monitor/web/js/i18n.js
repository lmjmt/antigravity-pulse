function t(key, vars) {
    const dict = I18N[currentLang] || I18N.zh;
    let text = Object.prototype.hasOwnProperty.call(dict, key)
        ? dict[key]
        : (Object.prototype.hasOwnProperty.call(I18N.zh, key) ? I18N.zh[key] : key);
    if (vars && typeof text === 'string') {
        Object.keys(vars).forEach(k => {
            text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k] ?? ''));
        });
    }
    return text;
}

function i18n(key, vars) {
    return t(key, vars);
}

function getRangeLabel(rangeKey) {
    const k = 'range.' + (rangeKey || 'all');
    const dict = I18N[currentLang] || I18N.zh;
    return Object.prototype.hasOwnProperty.call(dict, k) ? t(k) : (rangeKey || 'all');
}

function applyStaticI18n() {
    document.documentElement.lang = currentLang === 'en' ? 'en' : 'zh-CN';
    document.title = t('page.title');

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) el.setAttribute('placeholder', t(key));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        if (key) el.setAttribute('title', t(key));
    });

    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) {
        langBtn.textContent = t('nav.lang_btn');
        langBtn.title = t('nav.lang_title');
    }

    const rangeBadge = document.getElementById('task-range-badge');
    if (rangeBadge && typeof currentTimeRange !== 'undefined') {
        rangeBadge.innerText = `🕒 ${getRangeLabel(currentTimeRange)}`;
    }
}

function toggleLanguage() {
    currentLang = currentLang === 'zh' ? 'en' : 'zh';
    if (typeof lastAnalyticsSig !== 'undefined') lastAnalyticsSig = null;
    if (typeof lastSessionsSig !== 'undefined') lastSessionsSig = null;
    if (typeof lastMultiTaskSig !== 'undefined') lastMultiTaskSig = null;
    if (typeof lastQuotaSig !== 'undefined') lastQuotaSig = null;
    if (typeof sessionModelFilter !== 'undefined') sessionModelFilter = '';

    applyStaticI18n();
    if (typeof fetchUpdates === 'function') fetchUpdates();
    if (typeof activeDrawerCid !== 'undefined' && activeDrawerCid && typeof openContextDrawer === 'function') {
        openContextDrawer(activeDrawerCid);
    }
    if (typeof inspActiveTargetCid !== 'undefined' && inspActiveTargetCid && typeof loadTaskStepsWindow === 'function') {
        loadTaskStepsWindow(
            inspActiveTargetCid,
            typeof inspHighlightStep !== 'undefined' ? inspHighlightStep : null,
            typeof inspActiveSubagentName !== 'undefined' ? inspActiveSubagentName : null
        );
    }
}
